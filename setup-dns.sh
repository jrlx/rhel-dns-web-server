#!/bin/bash
# our script to configure BIND DNS on the server

set -euo pipefail
cd "$(dirname "$0")"

if [ "$EUID" -ne 0 ]; then
  echo "Run this script with sudo." >&2
  exit 1
fi

source ./config.env
[ -f ./config.env.local ] && source ./config.env.local

# from the config.env
SERVER_NAME="${SERVER_NAME:-server.$DOMAIN}"
CLIENT_NAME="${CLIENT_NAME:-client.$DOMAIN}"
NS_NAME="ns1.$DOMAIN"

IFS=. read -r O1 O2 O3 _ <<< "$SERVER_IP"
LAB_NET="$O1.$O2.$O3.0/24"
REV_ZONE="$O3.$O2.$O1.in-addr.arpa"
SERVER_OCTET="${SERVER_IP##*.}"
CLIENT_OCTET="${CLIENT_IP##*.}"

FWD_FILE="/var/named/$DOMAIN.zone"
REV_FILE="/var/named/$REV_ZONE.zone"
ZONES_CONF="/etc/named/lab.zones"

# Epoch seconds always increase, so the zone serial goes up on every run.
SERIAL="$(date +%s)"

echo "==> Setting up DNS for $DOMAIN on $SERVER_IP (lab network $LAB_NET)"

# 1. Install packages
dnf install -y bind bind-utils

# 2. Let named listen on the lab network

# Keep one copy of RHEL's original config for reference and recovery.
cp -n /etc/named.conf /etc/named.conf.orig

sed -i -E "s|^\s*listen-on port 53 \{.*\};|\tlisten-on port 53 { 127.0.0.1; $SERVER_IP; };|" /etc/named.conf
sed -i -E "s|^\s*allow-query\s+\{.*\};|\tallow-query     { localhost; $LAB_NET; };|" /etc/named.conf

# Point named.conf at our zone declarations (only added once)
INCLUDE_LINE="include \"$ZONES_CONF\";"
grep -qF "$INCLUDE_LINE" /etc/named.conf || echo "$INCLUDE_LINE" >> /etc/named.conf

# 3. Declare the forward and reverse zones
mkdir -p /etc/named
cat > "$ZONES_CONF" <<EOF
// Lab zones - generated by setup-dns.sh
zone "$DOMAIN" IN {
    type master;
    file "$DOMAIN.zone";
    allow-update { none; };
};

zone "$REV_ZONE" IN {
    type master;
    file "$REV_ZONE.zone";
    allow-update { none; };
};
EOF

# ---------- 4. Forward zone: names -> IPs ----------
cat > "$FWD_FILE" <<EOF
\$TTL 86400
@   IN  SOA $NS_NAME. admin.$DOMAIN. (
        $SERIAL ; serial
        3600    ; refresh
        1800    ; retry
        604800  ; expire
        86400 ) ; minimum TTL

@               IN  NS  $NS_NAME.

$NS_NAME.       IN  A   $SERVER_IP
$SERVER_NAME.   IN  A   $SERVER_IP
$CLIENT_NAME.   IN  A   $CLIENT_IP
$SITE1.         IN  A   $SERVER_IP
$SITE2.         IN  A   $SERVER_IP
EOF

# 5. Reverse zone: IPs -> names
cat > "$REV_FILE" <<EOF
\$TTL 86400
@   IN  SOA $NS_NAME. admin.$DOMAIN. (
        $SERIAL ; serial
        3600    ; refresh
        1800    ; retry
        604800  ; expire
        86400 ) ; minimum TTL

@                IN  NS   $NS_NAME.

$SERVER_OCTET    IN  PTR  $SERVER_NAME.
$CLIENT_OCTET    IN  PTR  $CLIENT_NAME.
EOF

# 6. Ownership, permissions, SELinux
chown root:named "$ZONES_CONF" "$FWD_FILE" "$REV_FILE"
chmod 640 "$ZONES_CONF" "$FWD_FILE" "$REV_FILE"
restorecon -Rv /etc/named.conf /etc/named /var/named

# 7. Validate before restarting
named-checkconf
named-checkzone "$DOMAIN" "$FWD_FILE"
named-checkzone "$REV_ZONE" "$REV_FILE"

# 8. Firewall
systemctl enable --now firewalld
firewall-cmd --permanent --add-service=dns
firewall-cmd --reload

# 9. Start named and enable it at boot
systemctl enable named
systemctl restart named

# Quick self-test
echo "==> Test lookups against $SERVER_IP:"
for name in "$SERVER_NAME" "$CLIENT_NAME" "$SITE1" "$SITE2"; do
  printf '  %-25s -> %s\n' "$name" "$(dig @"$SERVER_IP" "$name" +short)"
done
printf '  %-25s -> %s\n' "$SERVER_IP" "$(dig @"$SERVER_IP" -x "$SERVER_IP" +short)"
printf '  %-25s -> %s\n' "$CLIENT_IP" "$(dig @"$SERVER_IP" -x "$CLIENT_IP" +short)"

echo "==> DNS setup complete."
